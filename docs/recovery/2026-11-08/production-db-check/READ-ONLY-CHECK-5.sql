), live_cols AS (
  SELECT table_name AS t, column_name AS c,
         udt_name || CASE WHEN is_nullable='NO' THEN ' NOT NULL' ELSE '' END || coalesce(' DEFAULT ' || column_default, '') AS def
  FROM information_schema.columns WHERE table_schema='public'
), live_enum AS (
  SELECT t.typname AS typ, e.enumlabel AS label FROM pg_type t JOIN pg_namespace n ON n.oid=t.typnamespace JOIN pg_enum e ON e.enumtypid=t.oid WHERE n.nspname='public'
)
SELECT
  (SELECT json_agg(DISTINCT t ORDER BY t) FROM exp_cols WHERE t NOT IN (SELECT table_name FROM information_schema.tables WHERE table_schema='public')) AS missing_tables,
  (SELECT json_agg(e.t || '.' || e.c || ' :: ' || e.def ORDER BY e.t, e.c) FROM exp_cols e
     WHERE e.t IN (SELECT table_name FROM information_schema.tables WHERE table_schema='public')
       AND NOT EXISTS (SELECT 1 FROM live_cols l WHERE l.t=e.t AND l.c=e.c)) AS missing_columns,
  (SELECT json_agg(e.t || '.' || e.c || ' expected [' || e.def || '] live [' || l.def || ']' ORDER BY e.t, e.c) FROM exp_cols e JOIN live_cols l ON l.t=e.t AND l.c=e.c WHERE l.def <> e.def) AS mismatched_columns,
  (SELECT json_agg(name ORDER BY name) FROM exp_idx WHERE name NOT IN (SELECT indexname FROM pg_indexes WHERE schemaname='public')) AS missing_indexes,
  (SELECT json_agg(typ || ':' || label ORDER BY typ, label) FROM exp_enum x WHERE NOT EXISTS (SELECT 1 FROM live_enum l WHERE l.typ=x.typ AND l.label=x.label)) AS missing_enum_values,
  (SELECT json_agg(l.t || '.' || l.c ORDER BY l.t, l.c) FROM live_cols l WHERE l.t IN (SELECT t FROM exp_cols) AND NOT EXISTS (SELECT 1 FROM exp_cols e WHERE e.t=l.t AND e.c=l.c)) AS extra_live_columns,
  (SELECT count(DISTINCT t) FROM exp_cols) AS expected_tables;
