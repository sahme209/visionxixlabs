/**
 * Metrics taxonomy + in-process counters.
 *
 * The platform doesn't yet ship with Prometheus / StatsD. This module gives
 * every subsystem one place to increment named counters and inspect rolling
 * totals — the Reliability/Observability centers read from here, and a
 * future exporter can wire stdout/Prom/OTel without changing call sites.
 *
 * Counters are tenant-scoped where the metric depends on a tenant (scans,
 * findings, exports, audit). Counters that describe the *platform* (auth
 * failures, redaction events) are not — they roll up across tenants.
 */

