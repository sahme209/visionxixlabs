// ---------------------------------------------------------------------------
// In-process counter store
// ---------------------------------------------------------------------------

interface CounterKey {
  metric: MetricId;
  tenant?: OrganizationId;
}

function compositeKey(key: CounterKey): string {
  return `${key.metric}::${key.tenant ?? "_platform"}`;
}

const _counters = new Map<string, number>();

export interface RecordOptions {
  /** Required for tenant-scoped metrics. */
  organizationId?: OrganizationId;
  /** Increment by this much. Defaults to 1. */
  by?: number;
}

export function record(metric: MetricId, opts: RecordOptions = {}): void {
  const spec = METRIC_SPECS[metric];
  if (!spec) return;
  const tenant = spec.tenantScoped ? opts.organizationId : undefined;
  if (spec.tenantScoped && !tenant) {
    // Tenant-scoped metrics without a tenant land in a "_unknown" bucket so
    // we can spot the gap rather than silently swallowing the signal.
    const key = compositeKey({ metric, tenant: "_unknown" as unknown as OrganizationId });
    _counters.set(key, (_counters.get(key) ?? 0) + (opts.by ?? 1));
    return;
  }
  const key = compositeKey({ metric, tenant });
  _counters.set(key, (_counters.get(key) ?? 0) + (opts.by ?? 1));
}

export function reset(): void { _counters.clear(); }

export interface CounterSnapshot {
  metric: MetricId;
  tenant?: OrganizationId;
  value: number;
  unit: MetricUnit;
  description: string;
}

/** Read a single counter — used by the Observability Center UI. */
export function read(metric: MetricId, tenant?: OrganizationId): CounterSnapshot {
  const spec = METRIC_SPECS[metric];
  const t = spec.tenantScoped ? tenant : undefined;
  const value = _counters.get(compositeKey({ metric, tenant: t })) ?? 0;
  return { metric, tenant: t, value, unit: spec.unit, description: spec.description };
}

/** Read every counter for a tenant (or platform-wide). */
export function readAll(tenant?: OrganizationId): CounterSnapshot[] {
  return (Object.keys(METRIC_SPECS) as MetricId[]).map((m) => read(m, tenant));
}

/** Read every counter for a tenant grouped by domain prefix. */
export function readGrouped(tenant?: OrganizationId): Record<string, CounterSnapshot[]> {
  const groups: Record<string, CounterSnapshot[]> = {};
  for (const snap of readAll(tenant)) {
    const prefix = snap.metric.split(".")[0];
    (groups[prefix] ?? (groups[prefix] = [])).push(snap);
  }
  return groups;
}
