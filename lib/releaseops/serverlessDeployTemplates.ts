/**
 * Serverless deployment workflow templates (parity: Lambda, Cloud Run, Azure Functions). Pure.
 *
 * Like the Kubernetes templates: a GitHub Actions workflow the team commits to its own repository,
 * dispatched by V19 only after the environment's policy, checks, rings, change window and approvals
 * pass. Cloud access uses the platform's own short-lived OIDC federation configured in the customer's
 * account; V19 holds no cloud credentials. Every template shifts traffic gradually where the platform
 * supports it and keeps the previous version for instant rollback. Only the provider's official CLI is
 * used, plus the provider's official login action pinned by full commit SHA.
 */

export type ServerlessPlatform = "aws_lambda" | "gcp_cloud_run" | "azure_functions";
export const SERVERLESS_PLATFORMS: ReadonlyArray<{ id: ServerlessPlatform; label: string; summary: string }> = [
  { id: "aws_lambda", label: "AWS Lambda", summary: "Publish a new version from a container image, send it a share of the traffic on the live alias, and move all traffic back if that version reports errors; otherwise send it all traffic. Needs an alias named live." },
  { id: "gcp_cloud_run", label: "Google Cloud Run", summary: "Deploy a new revision with no traffic, send it a share of traffic, watch it, then send it all traffic; the previous revision stays for instant rollback." },
  { id: "azure_functions", label: "Azure Functions", summary: "Deploy to a staging slot, check its health endpoint, then swap it into production; swap back to roll back." },
];
export interface ServerlessTemplateInput { platform: ServerlessPlatform; name: string; region: string; canaryPercent?: number; observeMinutes?: number; resourceGroup?: string; healthPath?: string }
export type ServerlessTemplateResult = { ok: true; filename: string; yaml: string } | { ok: false; error: string };

// Official actions pinned by full commit SHA (tag in comment), never by tag alone. Verified against each
// repository's tag list on 2026-11-26.
const AWS_CREDENTIALS = "aws-actions/configure-aws-credentials@45666896f5d8e0f10ae255413f3a4cdd03bdc8f5 # v6.3.1";
const GCP_AUTH = "google-github-actions/auth@7c6bc770dae815cd3e89ee6cdf493a5fab2cc093 # v3.0.0";
const AZURE_LOGIN = "azure/login@a641126d1b8aa4d1fa005f4f92df94a3a4c4c906 # v3.1.0";

const NAME = /^[A-Za-z0-9][A-Za-z0-9_-]{0,62}$/;
const REGION = /^[a-z0-9-]{2,30}$/;
const HEALTH = /^\/[A-Za-z0-9/_.-]{0,100}$/;
const IMAGE_CHECK = `[[ "$IMAGE" =~ ^[a-z0-9]([a-z0-9._/:-]{0,250})(@sha256:[0-9a-f]{64})?$ ]] || { echo "Image reference is not allowed."; exit 1; }`;

export function serverlessDeployWorkflow(input: ServerlessTemplateInput): ServerlessTemplateResult {
  const platform = SERVERLESS_PLATFORMS.find((p) => p.id === input.platform);
  if (!platform) return { ok: false, error: "Choose AWS Lambda, Google Cloud Run or Azure Functions." };
  if (!NAME.test(input.name)) return { ok: false, error: "The service or function name may use letters, digits, hyphens and underscores." };
  if (!REGION.test(input.region)) return { ok: false, error: "Enter a region such as us-east-1, europe-west1 or eastus." };
  const percent = Math.min(Math.max(Math.trunc(input.canaryPercent ?? 10), 1), 50);
  const observe = Math.min(Math.max(Math.trunc(input.observeMinutes ?? 5), 1), 60);
  const header = (permissions: string, inputsExtra = "") => `name: V19 ${platform.label} deploy (${input.name})

# Generated by V19. Dispatched by V19 after its policy, checks and approvals pass.
# Cloud access uses short-lived OIDC federation set up in your cloud account; no keys are stored.
on:
  workflow_dispatch:
    inputs:
      image:
        description: Container image to deploy (prefer a digest)
        required: true
        type: string${inputsExtra}

permissions:
${permissions}

concurrency:
  group: v19-serverless-${input.platform}-${input.name}
  cancel-in-progress: false

jobs:
  deploy:
    runs-on: ubuntu-latest
    timeout-minutes: ${observe + 30}
    env:
      NAME: ${input.name}
      REGION: ${input.region}
      IMAGE: \${{ inputs.image }}
    steps:
      - name: Check the image reference
        run: |
          ${IMAGE_CHECK}
`;
  const oidc = "  contents: read\n  id-token: write";
  if (input.platform === "aws_lambda") {
    const yaml = header(oidc) + `      - name: Assume the deploy role (OIDC)
        uses: ${AWS_CREDENTIALS}
        with:
          role-to-assume: \${{ vars.V19_AWS_DEPLOY_ROLE_ARN }}
          aws-region: ${input.region}
      - name: Publish a new version
        id: publish
        run: |
          aws lambda update-function-code --function-name "$NAME" --image-uri "$IMAGE" > /dev/null
          aws lambda wait function-updated --function-name "$NAME"
          PREVIOUS=$(aws lambda get-alias --function-name "$NAME" --name live --query FunctionVersion --output text)
          NEW=$(aws lambda publish-version --function-name "$NAME" --query Version --output text)
          echo "previous=$PREVIOUS" >> "$GITHUB_OUTPUT"; echo "new=$NEW" >> "$GITHUB_OUTPUT"
      - name: Shift ${percent}% of traffic and watch for ${observe} minutes
        env:
          PREVIOUS: \${{ steps.publish.outputs.previous }}
          NEW: \${{ steps.publish.outputs.new }}
        run: |
          aws lambda update-alias --function-name "$NAME" --name live --function-version "$PREVIOUS" --routing-config "{\\"AdditionalVersionWeights\\":{\\"$NEW\\":${(percent / 100).toFixed(2)}}}" > /dev/null
          sleep ${observe * 60}
          ERRORS=$(aws cloudwatch get-metric-statistics --namespace AWS/Lambda --metric-name Errors --dimensions Name=FunctionName,Value="$NAME" Name=Resource,Value="$NAME:live" Name=ExecutedVersion,Value="$NEW" --start-time "$(date -u -d '-${observe + 1} minutes' +%Y-%m-%dT%H:%M:%SZ)" --end-time "$(date -u +%Y-%m-%dT%H:%M:%SZ)" --period 60 --statistics Sum --query 'sum(Datapoints[].Sum)' --output text)
          if [ "\${ERRORS:-0}" != "None" ] && [ "\${ERRORS%.*}" -gt 0 ]; then
            echo "The new version reported errors; moving all traffic back."
            aws lambda update-alias --function-name "$NAME" --name live --function-version "$PREVIOUS" --routing-config '{"AdditionalVersionWeights":{}}' > /dev/null
            exit 1
          fi
      - name: Send all traffic to the new version
        env:
          NEW: \${{ steps.publish.outputs.new }}
        run: aws lambda update-alias --function-name "$NAME" --name live --function-version "$NEW" --routing-config '{"AdditionalVersionWeights":{}}' > /dev/null
`;
    return { ok: true, filename: `v19-lambda-${input.name}.yml`, yaml };
  }
  if (input.platform === "gcp_cloud_run") {
    const yaml = header(oidc) + `      - name: Authenticate (Workload Identity Federation)
        uses: ${GCP_AUTH}
        with:
          workload_identity_provider: \${{ vars.V19_GCP_WORKLOAD_IDENTITY_PROVIDER }}
          service_account: \${{ vars.V19_GCP_DEPLOY_SERVICE_ACCOUNT }}
      - name: Deploy a new revision with no traffic
        run: gcloud run deploy "$NAME" --image "$IMAGE" --region "$REGION" --no-traffic --tag candidate --quiet
      - name: Send ${percent}% of traffic and watch for ${observe} minutes
        run: |
          gcloud run services update-traffic "$NAME" --region "$REGION" --to-tags candidate=${percent} --quiet
          for i in $(seq 1 ${observe}); do
            sleep 60
            READY=$(gcloud run services describe "$NAME" --region "$REGION" --format 'value(status.conditions[0].status)')
            if [ "$READY" != "True" ]; then echo "Service is not ready; sending all traffic back."; gcloud run services update-traffic "$NAME" --region "$REGION" --to-tags candidate=0 --quiet; exit 1; fi
          done
      - name: Send all traffic to the new revision
        run: gcloud run services update-traffic "$NAME" --region "$REGION" --to-latest --quiet
`;
    return { ok: true, filename: `v19-cloud-run-${input.name}.yml`, yaml };
  }
  const rg = input.resourceGroup ?? "";
  if (!/^[A-Za-z0-9._()-]{1,90}$/.test(rg)) return { ok: false, error: "Enter the Azure resource group." };
  const health = input.healthPath ?? "/api/health";
  if (!HEALTH.test(health)) return { ok: false, error: "The health path must start with / and use only letters, digits and / _ . -" };
  const yaml = header(oidc) + `      - name: Sign in to Azure (OIDC)
        uses: ${AZURE_LOGIN}
        with:
          client-id: \${{ vars.V19_AZURE_CLIENT_ID }}
          tenant-id: \${{ vars.V19_AZURE_TENANT_ID }}
          subscription-id: \${{ vars.V19_AZURE_SUBSCRIPTION_ID }}
      - name: Deploy to the staging slot
        env:
          RG: ${rg}
        run: |
          az functionapp config container set --name "$NAME" --resource-group "$RG" --slot staging --image "$IMAGE" > /dev/null
          az functionapp restart --name "$NAME" --resource-group "$RG" --slot staging
      - name: Check the staging slot for ${observe} minutes
        env:
          RG: ${rg}
        run: |
          HOST=$(az functionapp show --name "$NAME" --resource-group "$RG" --slot staging --query defaultHostName --output tsv)
          for i in $(seq 1 ${observe}); do
            sleep 60
            CODE=$(curl -s -o /dev/null -w '%{http_code}' "https://$HOST${health}")
            if [ "$CODE" != "200" ]; then echo "Staging health check returned $CODE; not swapping."; exit 1; fi
          done
      - name: Swap staging into production
        env:
          RG: ${rg}
        run: az functionapp deployment slot swap --name "$NAME" --resource-group "$RG" --slot staging --target-slot production
`;
  return { ok: true, filename: `v19-azure-functions-${input.name}.yml`, yaml };
}
