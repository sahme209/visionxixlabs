/**
 * Kubernetes rollout workflow templates (parity item: rolling, blue/green and canary deployments).
 *
 * Pure: returns the GitHub Actions workflow a team commits to its own repository. V19 dispatches it
 * with workflow_dispatch like the ECS template, so the same gates (policy, checks, rings, change
 * windows, approvals) apply before anything runs. Cluster access stays in the customer's CI: the
 * workflow reads a KUBE_CONFIG repository secret; V19 never holds cluster credentials. Only kubectl,
 * which GitHub-hosted runners already include, is used; no third-party actions.
 *
 * Names are validated here and the image is validated inside the workflow before use, so no value
 * reaches a shell unchecked. `${{` never appears in generated text from user input.
 */

export type RolloutStrategy = "rolling" | "blue_green" | "canary";
export const ROLLOUT_STRATEGIES: ReadonlyArray<{ id: RolloutStrategy; label: string; summary: string }> = [
  { id: "rolling", label: "Rolling update", summary: "Replace pods gradually in one Deployment; undo the rollout automatically if it does not become ready." },
  { id: "blue_green", label: "Blue/green", summary: "Deploy to the idle colour, wait until it is ready, then switch the Service selector. The previous colour keeps running for instant switch-back." },
  { id: "canary", label: "Canary", summary: "Run the new image in a small canary Deployment behind the same Service, watch it, then promote to the main Deployment or scale the canary to zero." },
];
export interface RolloutTemplateInput { strategy: RolloutStrategy; namespace: string; deployment: string; container: string; canaryReplicas?: number; observeMinutes?: number; timeoutMinutes?: number }
export type RolloutTemplateResult = { ok: true; filename: string; yaml: string } | { ok: false; error: string };

const DNS_LABEL = /^[a-z0-9]([-a-z0-9]{0,61}[a-z0-9])?$/;
const IMAGE_CHECK = `[[ "$IMAGE" =~ ^[a-z0-9]([a-z0-9._/:-]{0,250})(@sha256:[0-9a-f]{64})?$ ]] || { echo "Image reference is not allowed."; exit 1; }`;

export function kubernetesRolloutWorkflow(input: RolloutTemplateInput): RolloutTemplateResult {
  const { strategy, namespace, deployment, container } = input;
  if (!ROLLOUT_STRATEGIES.some((s) => s.id === strategy)) return { ok: false, error: "Choose rolling, blue_green or canary." };
  for (const [label, v] of [["Namespace", namespace], ["Deployment", deployment], ["Container", container]] as const) {
    if (!DNS_LABEL.test(v)) return { ok: false, error: `${label} must be a Kubernetes name: lowercase letters, digits and hyphens.` };
  }
  if (deployment.length > 50) return { ok: false, error: "Deployment name must be at most 50 characters so -blue, -green and -canary names fit." };
  const timeout = Math.min(Math.max(Math.trunc(input.timeoutMinutes ?? 10), 1), 60);
  const canaryReplicas = Math.min(Math.max(Math.trunc(input.canaryReplicas ?? 1), 1), 10);
  const observe = Math.min(Math.max(Math.trunc(input.observeMinutes ?? 5), 1), 60);
  const header = `name: V19 Kubernetes ${ROLLOUT_STRATEGIES.find((s) => s.id === strategy)!.label} (${namespace}/${deployment})

# Generated by V19. Dispatched by V19 after its policy, checks and approvals pass.
# Cluster access stays here: add a KUBE_CONFIG repository secret scoped to namespace ${namespace}.
on:
  workflow_dispatch:
    inputs:
      image:
        description: Image reference to deploy (prefer a digest)
        required: true
        type: string

permissions:
  contents: read

concurrency:
  group: v19-k8s-${namespace}-${deployment}
  cancel-in-progress: false

jobs:
  deploy:
    runs-on: ubuntu-latest
    timeout-minutes: ${timeout + observe + 15}
    env:
      NS: ${namespace}
      DEPLOY: ${deployment}
      CONTAINER: ${container}
      IMAGE: \${{ inputs.image }}
    steps:
      - name: Configure cluster access
        env:
          KUBE_CONFIG: \${{ secrets.KUBE_CONFIG }}
        run: |
          ${IMAGE_CHECK}
          [ -n "$KUBE_CONFIG" ] || { echo "Add the KUBE_CONFIG repository secret."; exit 1; }
          mkdir -p "$HOME/.kube" && printf '%s' "$KUBE_CONFIG" > "$HOME/.kube/config" && chmod 600 "$HOME/.kube/config"
          kubectl version --client
`;
  const body: Record<RolloutStrategy, string> = {
    rolling: `      - name: Rolling update
        run: |
          kubectl -n "$NS" set image "deployment/$DEPLOY" "$CONTAINER=$IMAGE"
          if ! kubectl -n "$NS" rollout status "deployment/$DEPLOY" --timeout=${timeout}m; then
            echo "Rollout did not become ready; undoing."
            kubectl -n "$NS" rollout undo "deployment/$DEPLOY"
            kubectl -n "$NS" rollout status "deployment/$DEPLOY" --timeout=${timeout}m || true
            exit 1
          fi
`,
    blue_green: `      - name: Deploy to the idle colour
        id: idle
        run: |
          ACTIVE=$(kubectl -n "$NS" get service "$DEPLOY" -o jsonpath='{.spec.selector.slot}')
          case "$ACTIVE" in blue) IDLE=green;; green) IDLE=blue;; *) echo "Service $DEPLOY must select slot: blue or slot: green."; exit 1;; esac
          REPLICAS=$(kubectl -n "$NS" get deployment "$DEPLOY-$ACTIVE" -o jsonpath='{.spec.replicas}')
          kubectl -n "$NS" set image "deployment/$DEPLOY-$IDLE" "$CONTAINER=$IMAGE"
          kubectl -n "$NS" scale "deployment/$DEPLOY-$IDLE" --replicas="$REPLICAS"
          kubectl -n "$NS" rollout status "deployment/$DEPLOY-$IDLE" --timeout=${timeout}m
          echo "active=$ACTIVE" >> "$GITHUB_OUTPUT"; echo "idle=$IDLE" >> "$GITHUB_OUTPUT"
      - name: Switch traffic
        env:
          IDLE: \${{ steps.idle.outputs.idle }}
          ACTIVE: \${{ steps.idle.outputs.active }}
        run: |
          kubectl -n "$NS" patch service "$DEPLOY" --type merge -p "{\\"spec\\":{\\"selector\\":{\\"slot\\":\\"$IDLE\\"}}}"
          echo "Traffic now goes to $IDLE. $DEPLOY-$ACTIVE keeps running so you can switch back with the same patch."
`,
    canary: `      - name: Start canary
        run: |
          kubectl -n "$NS" set image "deployment/$DEPLOY-canary" "$CONTAINER=$IMAGE"
          kubectl -n "$NS" scale "deployment/$DEPLOY-canary" --replicas=${canaryReplicas}
          kubectl -n "$NS" rollout status "deployment/$DEPLOY-canary" --timeout=${timeout}m
      - name: Watch canary for ${observe} minutes
        run: |
          for i in $(seq 1 ${observe}); do
            sleep 60
            READY=$(kubectl -n "$NS" get deployment "$DEPLOY-canary" -o jsonpath='{.status.readyReplicas}')
            RESTARTS=$(kubectl -n "$NS" get pods -l "app=$DEPLOY,track=canary" -o jsonpath='{range .items[*]}{.status.containerStatuses[*].restartCount}{" "}{end}' | tr ' ' '\\n' | awk '{s+=$1} END {print s+0}')
            echo "minute $i: ready=$READY restarts=$RESTARTS"
            if [ "\${READY:-0}" -lt ${canaryReplicas} ] || [ "$RESTARTS" -gt 0 ]; then echo "Canary is not healthy."; exit 1; fi
          done
      - name: Promote
        run: |
          kubectl -n "$NS" set image "deployment/$DEPLOY" "$CONTAINER=$IMAGE"
          kubectl -n "$NS" rollout status "deployment/$DEPLOY" --timeout=${timeout}m
      - name: Scale canary to zero
        if: always()
        run: kubectl -n "$NS" scale "deployment/$DEPLOY-canary" --replicas=0
`,
  };
  const filename = `v19-k8s-${strategy.replace("_", "-")}-${deployment}.yml`;
  return { ok: true, filename, yaml: header + body[strategy] };
}
