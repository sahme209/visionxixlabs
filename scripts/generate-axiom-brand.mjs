import {createHash} from 'node:crypto';
import {readFileSync,writeFileSync} from 'node:fs';
import sharp from 'sharp';
const source=readFileSync(new URL('../assets/brand/axiom-white-source.png',import.meta.url));
const {width,height}=await sharp(source).metadata();
// Use the supplied pixels as a luminance mask, without tracing or redrawing.
const svg=`<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}"><defs><filter id="clean"><feComponentTransfer><feFuncR type="discrete" tableValues="0 1"/><feFuncG type="discrete" tableValues="0 1"/><feFuncB type="discrete" tableValues="0 1"/></feComponentTransfer></filter><mask id="mark" mask-type="luminance"><image filter="url(#clean)" href="data:image/png;base64,${source.toString('base64')}" width="${width}" height="${height}"/></mask></defs><rect width="100%" height="100%" fill="white" mask="url(#mark)"/></svg>`;
writeFileSync(new URL('../assets/brand/axiom-white.svg',import.meta.url),svg);
const png=await sharp(Buffer.from(svg)).png().toBuffer();
for(const path of ['public/vision-xix-logo.png','desktop/public/axiom-logo.png'])writeFileSync(new URL('../'+path,import.meta.url),png);
for(const [path,size] of [['public/favicon-32x32.png',32],['public/apple-icon.png',180],['app/apple-icon.png',180],['app/icon.png',512],['desktop/src-tauri/icons/32x32.png',32],['desktop/src-tauri/icons/64x64.png',64],['desktop/src-tauri/icons/128x128.png',128],['desktop/src-tauri/icons/128x128@2x.png',256]])writeFileSync(new URL('../'+path,import.meta.url),await sharp(png).resize(size,size,{fit:'contain'}).png().toBuffer());

writeFileSync(new URL('../desktop/src-tauri/icons/icon.png',import.meta.url),await sharp(png).resize(1024,1024,{fit:'contain',background:'#00000000'}).png().toBuffer());

// New filenames, rather than only query strings, give browsers fresh icon identities.
const version=createHash('sha256').update(png).digest('hex').slice(0,12);
const iconUrls=[];
for(const [sourcePath,kind] of [['public/favicon-32x32.png','favicon'],['app/icon.png','icon'],['public/apple-icon.png','apple-icon']]){
 const bytes=readFileSync(new URL('../'+sourcePath,import.meta.url));
 const name=`axiom-${kind}-${createHash('sha256').update(bytes).digest('hex').slice(0,12)}.png`;
 writeFileSync(new URL('../public/'+name,import.meta.url),bytes);iconUrls.push('/'+name);
}
writeFileSync(new URL('../lib/brandAssets.ts',import.meta.url),`// Generated by scripts/generate-axiom-brand.mjs from the canonical transparent mark.
export const AXIOM_ICON_VERSION = ${JSON.stringify(version)};
export const AXIOM_FAVICON_URL = ${JSON.stringify(iconUrls[0])};
export const AXIOM_APP_ICON_URL = ${JSON.stringify(iconUrls[1])};
export const AXIOM_APPLE_ICON_URL = ${JSON.stringify(iconUrls[2])};
`);
