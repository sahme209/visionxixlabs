// Website favicon and app icons from the vxix code mark (the boxed "</>" in the top-left of the site).
// White mark on a dark rounded square so it reads on light and dark browser tabs. Website only: the
// desktop app keeps its own V19 icon. Run: node scripts/generate-vxix-site-icons.mjs
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import sharp from "sharp";

const root = new URL("../", import.meta.url);
const mark = readFileSync(new URL("public/brand/vxix-mark.svg", root), "utf8");
const inner = mark.match(/<g[\s\S]*<\/g>/)[0];

/** Square icon: dark tile (rounded unless `square`), the 56x54 mark centred at about 70% of the width. */
function iconSvg({ square = false, small = false } = {}) {
  // At favicon size the mark fills more of the tile with heavier strokes so it stays legible.
  const size = 512, markW = small ? 452 : 360, scale = markW / 56, markH = 54 * scale;
  const x = (size - markW) / 2, y = (size - markH) / 2;
  const tile = square ? `<rect width="${size}" height="${size}" fill="#0a0908"/>` : `<rect width="${size}" height="${size}" rx="112" fill="#0a0908"/>`;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">${tile}<g transform="translate(${x} ${y}) scale(${scale})">${small ? inner.replace('stroke-width="3"', 'stroke-width="4.2"') : inner}</g></svg>`;
}

const rounded = Buffer.from(iconSvg());
const square = Buffer.from(iconSvg({ square: true })); // Apple adds its own corner mask.
const small = Buffer.from(iconSvg({ small: true }));
const png = (svg, s) => sharp(svg, { density: 300 }).resize(s, s).png({ compressionLevel: 9 }).toBuffer();

const outputs = [["public/favicon-32x32.png", small, 32], ["app/icon.png", rounded, 512], ["public/apple-icon.png", square, 180], ["app/apple-icon.png", square, 180]];
for (const [path, svg, s] of outputs) writeFileSync(new URL(path, root), await png(svg, s));

// New filenames give browsers fresh icon identities (they cache favicons aggressively).
const urls = [];
for (const [source, kind] of [["public/favicon-32x32.png", "favicon"], ["app/icon.png", "icon"], ["public/apple-icon.png", "apple-icon"], [null, "icon-192"]]) {
  const bytes = source ? readFileSync(new URL(source, root)) : await png(rounded, 192);
  const name = `axiom-${kind}-${createHash("sha256").update(bytes).digest("hex").slice(0, 12)}.png`;
  writeFileSync(new URL(`public/${name}`, root), bytes);
  urls.push(`/${name}`);
}
const version = createHash("sha256").update(rounded).digest("hex").slice(0, 12);
writeFileSync(new URL("lib/brandAssets.ts", root), `// Generated by scripts/generate-vxix-site-icons.mjs from public/brand/vxix-mark.svg.
export const AXIOM_ICON_VERSION = ${JSON.stringify(version)};
export const AXIOM_FAVICON_URL = ${JSON.stringify(urls[0])};
export const AXIOM_APP_ICON_URL = ${JSON.stringify(urls[1])};
export const AXIOM_APPLE_ICON_URL = ${JSON.stringify(urls[2])};
export const AXIOM_APP_ICON_192_URL = ${JSON.stringify(urls[3])};
`);
console.log(urls.join("\n"));
