#!/usr/bin/env python3
"""Generate four offline reporting views; source classifications confer no authority."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import sys
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
MASTER = 'docs/product/axiom-master-action-plan.md'
BOARD = 'docs/product/current-execution-board.md'
OUT = 'docs/product/plan-views'
PARENTS = {*(f'A{i}' for i in range(1, 10)), *(f'B{i}' for i in range(1, 7)), *(f'C{i}' for i in range(1, 7))}
CLASSES = {'implemented', 'local-only', 'simulated', 'planned', 'disabled', 'live-accepted'}
CANDIDATES = ('Taste Skill', 'Web Design Guidelines', 'Awesome Design', 'Image-to-Code', 'Playwright', 'React Bits', 'GSAP', 'Lenis', 'GetLayers', 'Prompt Motion', 'OPA', 'Conftest', 'OpenTelemetry', 'Promptfoo', 'Langfuse', 'Temporal')


def table_rows(text):
    for line in text.splitlines():
        if line.startswith('|') and not re.match(r'^\|\s*:?-', line):
            yield [cell.strip() for cell in line.strip().strip('|').split('|')]


def parse_board(text):
    rows = {}
    for cells in table_rows(text):
        if len(cells) < 3 or not re.match(r'^\[ \] [ABC]\d+\b', cells[1]):
            continue
        parent = re.match(r'^\[ \] ([ABC]\d+)\b', cells[1])[1]
        if parent not in PARENTS or parent in rows:
            raise ValueError('unknown or duplicate parent: ' + parent)
        tags = re.findall(r'<!-- evidence: ([a-z,-]+) -->', ' '.join(cells))
        if len(tags) != 1 or len(set(tags[0].split(','))) != len(tags[0].split(',')) or not set(tags[0].split(',')) <= CLASSES:
            raise ValueError('one known evidence class required: ' + parent)
        if parent.startswith('C') and tags[0] != 'planned':
            raise ValueError('future C parent must remain planned: ' + parent)
        rows[parent] = (cells, tags[0])
    if set(rows) != PARENTS:
        raise ValueError('missing parents: ' + ', '.join(sorted(PARENTS - set(rows))))
    return rows


def section(text, heading):
    match = re.search(r'^## ' + re.escape(heading) + r'\s*\n(.*?)(?=^## |\Z)', text, re.M | re.S)
    if not match:
        raise ValueError('missing board section: ' + heading)
    return match[1].strip()


def local_links(root, paths, generated=None):
    """Check literal Markdown local targets, not external availability or acceptance."""
    root = root.resolve()
    generated = generated or {}
    failures = []
    for relative in paths:
        body = generated.get(relative)
        if body is None:
            body = (root / relative).read_text()
        for raw in re.findall(r'\[[^\]\n]*\]\(([^)\n]+)\)', body):
            raw = raw.strip().strip('<>')
            target = urlsplit(raw)
            if target.scheme or target.netloc or not target.path:
                continue
            dest = ((root if target.path.startswith('/') else (root / relative).parent) / unquote(target.path).lstrip('/')).resolve()
            if not dest.is_relative_to(root.resolve()):
                failures.append(relative + ': outside repository: ' + raw)
            elif dest.relative_to(root).as_posix() not in generated and not dest.exists():
                failures.append(relative + ': missing: ' + raw)
    return failures


def moved_links(body, source):
    def move(match):
        label, raw = match.groups()
        target = urlsplit(raw)
        if target.scheme or target.netloc or raw.startswith(('#', '/')):
            return match[0]
        # Views live one directory below the source board/master.
        return '[' + label + '](../' + raw + ')'
    return re.sub(r'\[([^\]\n]*)\]\(([^)\n]+)\)', move, body)


def render(root):
    master = (root / MASTER).read_text()
    board = (root / BOARD).read_text()
    rows = parse_board(board)
    # Reject novel identifiers even when table formatting changes.
    headings = set(re.findall(r'^### ([ABC]\d+)\.', master, re.M))
    if headings - PARENTS:
        raise ValueError('unknown master parent headings')
    decisions = section(board, 'Current dependency and decision source register')
    expected = ['Decision', 'Owner', 'Selected / state', 'Alternative', 'Reason / evidence', 'Reversibility', 'Recorded']
    decision_rows = list(table_rows(decisions))
    if not decision_rows or decision_rows[0] != expected or any(len(row) != len(expected) for row in decision_rows):
        raise ValueError('invalid decision table columns')
    packet = section(board, 'Current execution unit')
    if not re.search(r'\[[^\]]+\]\([^)]+\)', packet):
        raise ValueError('current unit packet link required')
    stamp = '\n'.join(f'- `{p}` SHA256 `{hashlib.sha256((root / p).read_bytes()).hexdigest()}`' for p in [MASTER, BOARD, 'package.json', 'desktop/package.json'])
    head = '# {title}\n\nGenerated by `scripts/generate-plan-views.py`; edit the source master/board/manifests, then regenerate. Reporting only; no permission, parent completion, percentage or customer acceptance is inferred. External links/browser availability remain unverified.\n\nSources:\n' + stamp + '\n\n'
    def view(name, title, body): return (f'{OUT}/{name}.md', head.format(title=title) + body.rstrip() + '\n')
    matrix = '| Parent | Explicit bounded evidence class | Recorded bounded work | Next gate |\n| --- | --- | --- | --- |\n'
    gates = ''
    for parent, (cells, classification) in rows.items():
        clean = [re.sub(r'<!-- evidence: [a-z,-]+ -->', '', c).strip() for c in cells]
        evidence, gate = (clean[2], clean[3]) if len(clean) == 4 else ('Planned / not authorized for implementation', clean[2])
        matrix += f'| {parent} | {classification} | {moved_links(evidence, BOARD)} | {moved_links(gate, BOARD)} |\n'
        gates += f'- **{parent}**: {moved_links(gate, BOARD)}\n'
    adoption = 'Direct package declarations only; ranges/file references are not resolved pins, installed-version evidence or new approval. License, maintenance and network/telemetry behavior are unverified here. Native, transitive, global tools and runtime use remain open inventory scopes.\n\n| Manifest | Group | Package | Declared range | License / review |\n| --- | --- | --- | --- | --- |\n'
    for manifest in ['package.json', 'desktop/package.json']:
        data = json.loads((root / manifest).read_text())
        for group in ['dependencies', 'devDependencies', 'optionalDependencies', 'peerDependencies']:
            for name, version in sorted(data.get(group, {}).items()):
                adoption += f'| `{manifest}` | {group} | `{name}` | `{version}` | Unverified; declaration only |\n'
    adoption += '\n## Proposed candidates, not adopted by this report\n\n'
    for candidate in CANDIDATES:
        if candidate in master:
            adoption += f'- **{candidate}**: master-plan proposal/evaluation reference; not adopted or installed by this report. Exact instruction/dependency/license/maintenance/network review and any required approval remain open.\n'
    return dict([view('capabilities', 'Product capability matrix', 'Classes describe the explicit bounded board evidence, not the whole parent. All original15 and future6 parents retain their separate acceptance gates.\n\n' + matrix), view('dependencies-decisions', 'Current dependency and decision source register', moved_links(decisions, BOARD) + '\n\n## Parent dependencies / next gates\n\n' + gates), view('execution-brief', 'Current execution brief', moved_links(packet, BOARD) + '\n\n## Top original priorities and gates\n\n' + '\n'.join(gates.splitlines()[:5]) + '\n\nFuture C1–C6 remain Planned / not authorized for implementation. Full requirements remain in [master](../axiom-master-action-plan.md) and [board](../current-execution-board.md).'), view('adoption-inventory', 'Adoption inventory', adoption)])


def update(root, check=False):
    root = root.resolve()
    generated = render(root)
    failures = local_links(root, [MASTER, BOARD, *generated], generated)
    if failures:
        raise ValueError('\n'.join(failures))
    drift = [p for p, body in generated.items() if not (root / p).is_file() or (root / p).read_text() != body]
    if check and drift:
        raise ValueError('generated view drift: ' + ', '.join(drift))
    for relative in generated:
        path = root / relative
        if path.is_symlink() or any(p.is_symlink() for p in path.parents if p != root.parent):
            raise ValueError('symlink output refused')
    if not check:
        for relative, body in generated.items():
            path = root / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(body)
    return len(generated)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        print(f'{update(ROOT, args.check)} source-derived views ' + ('current' if args.check else 'generated'))
    except (ValueError, OSError, json.JSONDecodeError) as error:
        print(str(error), file=sys.stderr)
        sys.exit(1)
