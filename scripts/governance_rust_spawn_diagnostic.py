def parse_probe(text):
 need(isinstance(text,str) and len(text)<1024,'probe_output_invalid')
 rows=text.splitlines();need(len(rows)==2 and text.endswith('\n'),'probe_output_invalid')
 result={}
 for label,row in zip(['ordinary','preexec'],rows):
  match=re.fullmatch(label+r':(exit-ok|exit-failed|spawn-error:(?:[0-9]{1,5}|unknown))',row)
  need(match is not None,'probe_output_invalid');value=match.group(1)
  if value.startswith('spawn-error:'):
   raw=value.split(':')[1];result[label]={'category':'spawn-error','errno':None if raw=='unknown' else int(raw)}
  else:result[label]={'category':value}
 return result

def classify_cargo(result,stderr):
 need(result.get('cleanup_confirmed') is True and result.get('status') in ['success','exit_nonzero'],'cargo_diagnostic_incomplete')
 if result['status']=='success':return 'tiny-compile-accepted'
 if 'could not execute process' in stderr and '(never executed)' in stderr:
  return 'compiler-launch-eperm' if 'Operation not permitted (os error 1)' in stderr else 'compiler-launch-other'
 if re.search(r'error\[E[0-9]+\]',stderr):return 'compiler-source-rejection'
 return 'cargo-error-unclassified'

def digest(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()

def verify_frozen(files):
 for path,want in files.items():
  path=Path(path);need(path.is_file() and not path.is_symlink() and digest(path)==want,'frozen_input_changed')

def freeze(files,path):
 path=Path(path);need(path.is_file() and not path.is_symlink(),'input_missing')
 want=digest(path);need(path not in files or files[path]==want,'input_rebound');files[path]=want

